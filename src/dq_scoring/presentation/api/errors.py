"""RFC 9457 Problem Details error models and centralized FastAPI exception handlers."""

from __future__ import annotations

import logging
from typing import Any

import psycopg
from fastapi import FastAPI, HTTPException, Request, status
from fastapi.exceptions import RequestValidationError
from fastapi.responses import JSONResponse
from pydantic import BaseModel, Field, ValidationError

logger = logging.getLogger(__name__)

PROBLEM_JSON_CONTENT_TYPE = "application/problem+json"


class ProblemDetails(BaseModel):
    """RFC 9457 standard problem details payload."""

    type: str = Field(
        default="about:blank",
        description="URI reference identifying the problem type",
    )
    title: str = Field(
        ...,
        description="Short, human-readable summary of the problem type",
    )
    status: int = Field(
        ...,
        description="The HTTP status code generated by the origin server",
    )
    detail: str = Field(
        ...,
        description="Human-readable explanation specific to this occurrence",
    )
    instance: str | None = Field(
        default=None,
        description="URI reference identifying the specific occurrence of the problem",
    )
    invalid_params: list[dict[str, Any]] | None = Field(
        default=None,
        description="List of specific input validation errors if applicable",
    )


def create_problem_response(
    status_code: int,
    title: str,
    detail: str,
    type_uri: str = "about:blank",
    instance: str | None = None,
    invalid_params: list[dict[str, Any]] | None = None,
    extensions: dict[str, Any] | None = None,
    headers: dict[str, str] | None = None,
) -> JSONResponse:
    """Construct an RFC 9457 compliant JSONResponse with application/problem+json media type.

    `extensions` become top-level members of the problem body (RFC 9457 §3.2).
    """
    problem = ProblemDetails(
        type=type_uri,
        title=title,
        status=status_code,
        detail=detail,
        instance=instance,
        invalid_params=invalid_params,
    )
    return JSONResponse(
        status_code=status_code,
        content={**problem.model_dump(exclude_none=True), **(extensions or {})},
        media_type=PROBLEM_JSON_CONTENT_TYPE,
        headers=headers,
    )


def register_exception_handlers(app: FastAPI) -> None:
    """Register RFC 9457 compliant exception handlers across FastAPI application."""

    @app.exception_handler(HTTPException)
    async def http_exception_handler(request: Request, exc: HTTPException) -> JSONResponse:
        title_map = {
            status.HTTP_400_BAD_REQUEST: "Bad Request",
            status.HTTP_401_UNAUTHORIZED: "Unauthorized",
            status.HTTP_403_FORBIDDEN: "Forbidden",
            status.HTTP_404_NOT_FOUND: "Not Found",
            status.HTTP_409_CONFLICT: "Conflict",
            status.HTTP_422_UNPROCESSABLE_ENTITY: "Unprocessable Entity",
        }
        title = title_map.get(exc.status_code, "HTTP Error")
        return create_problem_response(
            status_code=exc.status_code,
            title=title,
            detail=str(exc.detail),
            type_uri=f"urn:dq-scoring:error:{exc.status_code}",
            instance=request.url.path,
        )

    @app.exception_handler(RequestValidationError)
    async def validation_exception_handler(
        request: Request, exc: RequestValidationError
    ) -> JSONResponse:
        sanitized_errors: list[dict[str, Any]] = []
        for err in exc.errors():
            loc = ".".join(str(x) for x in err.get("loc", []))
            sanitized_errors.append({
                "name": loc,
                "reason": err.get("msg", "Invalid input value"),
            })
        return create_problem_response(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            title="Validation Error",
            detail="The request body or parameters failed schema validation.",
            type_uri="urn:dq-scoring:error:validation",
            instance=request.url.path,
            invalid_params=sanitized_errors,
        )

    @app.exception_handler(PermissionError)
    async def permission_error_handler(request: Request, exc: PermissionError) -> JSONResponse:
        return create_problem_response(
            status_code=status.HTTP_403_FORBIDDEN,
            title="Forbidden",
            detail=str(exc),
            type_uri="urn:dq-scoring:error:forbidden",
            instance=request.url.path,
        )

    @app.exception_handler(ValidationError)
    async def internal_validation_handler(request: Request, exc: ValidationError) -> JSONResponse:
        # A pydantic model built inside the server failed: a server bug, not client input.
        logger.exception("Internal model validation failed at %s", request.url.path)
        return create_problem_response(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            title="Internal Server Error",
            detail="An unexpected internal error occurred. Please contact system administrator.",
            type_uri="urn:dq-scoring:error:internal",
            instance=request.url.path,
        )

    @app.exception_handler(psycopg.errors.UniqueViolation)
    async def unique_violation_handler(request: Request, exc: psycopg.errors.UniqueViolation) -> JSONResponse:
        logger.info("Unique constraint conflict at %s: %s", request.url.path, exc.diag.constraint_name)
        return create_problem_response(
            status_code=status.HTTP_409_CONFLICT,
            title="Conflict",
            detail="The request conflicts with an existing record.",
            type_uri="urn:dq-scoring:error:409",
            instance=request.url.path,
        )

    @app.exception_handler(psycopg.errors.IntegrityError)
    async def integrity_error_handler(request: Request, exc: psycopg.errors.IntegrityError) -> JSONResponse:
        logger.info("Integrity constraint rejected input at %s: %s", request.url.path, exc.diag.constraint_name)
        return create_problem_response(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            title="Unprocessable Entity",
            detail="The request contains values that are not allowed.",
            type_uri="urn:dq-scoring:error:422",
            instance=request.url.path,
        )

    @app.exception_handler(ValueError)
    async def value_error_handler(request: Request, exc: ValueError) -> JSONResponse:
        return create_problem_response(
            status_code=status.HTTP_400_BAD_REQUEST,
            title="Invalid Argument",
            detail=str(exc),
            type_uri="urn:dq-scoring:error:bad-request",
            instance=request.url.path,
        )

    @app.exception_handler(KeyError)
    async def key_error_handler(request: Request, exc: KeyError) -> JSONResponse:
        return create_problem_response(
            status_code=status.HTTP_404_NOT_FOUND,
            title="Resource Not Found",
            detail=f"Resource key {exc} not found",
            type_uri="urn:dq-scoring:error:not-found",
            instance=request.url.path,
        )

    @app.exception_handler(Exception)
    async def generic_exception_handler(request: Request, exc: Exception) -> JSONResponse:
        # Sanitize: 0 byte stack trace leak, 0 SQL leak, log internally
        logger.exception("Unhandled server exception at %s: %s", request.url.path, exc)
        return create_problem_response(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            title="Internal Server Error",
            detail="An unexpected internal error occurred. Please contact system administrator.",
            type_uri="urn:dq-scoring:error:internal",
            instance=request.url.path,
        )
